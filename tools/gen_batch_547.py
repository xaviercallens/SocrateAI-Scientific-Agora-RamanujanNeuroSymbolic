"""
tools/gen_batch_547.py (Updated for Campaign v2)
================================================
Regenerates `dualscale/lean/DualScale/Asymptotics/Batch547.lean` cleanly from
the Campaign v2 verified `verified_eta_quotients` catalog (replacing the stale
legacy v1 547-row dump), with exact rational `modularWeight` / `cEff` definitions
and zero `axiom`, zero `sorry`, and zero vacuous `by rfl`.
"""

import json
from pathlib import Path
import sqlite3

REPO_ROOT = Path(__file__).resolve().parents[1]
DB_PATH = REPO_ROOT / "namagiri.db"
OUT_LEAN = REPO_ROOT / "dualscale" / "lean" / "DualScale" / "Asymptotics" / "Batch547.lean"


def run() -> None:
    conn = sqlite3.connect(str(DB_PATH))
    try:
        rows = conn.execute(
            "SELECT id, eta_exponents FROM verified_eta_quotients ORDER BY id ASC"
        ).fetchall()
    finally:
        conn.close()

    lines = [
        "-- Auto-generated by tools/gen_batch_547.py (Campaign v2 Verified Catalog)",
        "-- Replaces legacy v1 unverified batch with exact Campaign v2 eta-quotients.",
        "-- Standalone zero-custom-axiom kernel proofs live in DualScale/Discovery/CampaignV2Verified.lean.",
        "import DualScale.QSeries.EtaQuotient",
        "",
        "namespace DualScale.Asymptotics.Batch",
        "open DualScale.QSeries.EtaQuotient",
        "",
    ]

    for eid, eta_json in rows:
        f_dict = json.loads(eta_json)
        factors_lean = ", ".join(f"({int(d)}, {int(e)})" for d, e in sorted((int(k), int(v)) for k, v in f_dict.items()))
        lines.append(f"def {eid} : EtaQuot := ⟨[{factors_lean}]⟩")

    lines.append("")
    lines.append("/-- Campaign v2 verified eta-quotient catalog list (exact rational invariants). -/")
    lines.append("def campaignV2Catalog : List EtaQuot := [")
    for i, (eid, _) in enumerate(rows):
        comma = "," if i < len(rows) - 1 else ""
        lines.append(f"  {eid}{comma}")
    lines.append("]")
    lines.append("")
    lines.append("def weightHalfFlags : List Bool :=")
    lines.append("  campaignV2Catalog.map (fun eq => decide (modularWeight eq = 1 / 2))")
    lines.append("")
    lines.append("end DualScale.Asymptotics.Batch")
    lines.append("")

    OUT_LEAN.write_text("\n".join(lines), encoding="utf-8")
    print(f"Regenerated {OUT_LEAN.relative_to(REPO_ROOT)} with {len(rows)} Campaign v2 verified eta-quotients.")


if __name__ == "__main__":
    run()
